/**
 * Generates apps/docsite/src/generated/spacingUsage.ts
 *
 * Answers "if I change --spacing-N, what moves?" for the Theme Editor
 * (issue #808), read straight out of packages/core component source. Runs as
 * part of `pnpm generate` (before dev/build/test) so the map cannot drift from
 * the components it describes — the same reason scripts/generate-scope.mjs
 * derives the playground scope instead of maintaining a list.
 *
 * Run: node scripts/generate-spacing-usage.mjs
 */

import {writeFileSync, mkdirSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {deriveSpacingUsage} from '../src/lib/spacingUsage.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const CORE_SRC = resolve(ROOT, '../../packages/core/src');
const OUT = resolve(ROOT, 'src/generated/spacingUsage.ts');

const HEADER = `// Copyright (c) Meta Platforms, Inc. and affiliates.

// @generated by scripts/generate-spacing-usage.mjs — do not edit manually

/**
 * Which components a spacing token moves.
 *
 * - \`components\` — the token is used in a fixed style. Changing it moves
 *   these components with no props involved.
 * - \`viaProps\` — the token is one rung of a prop-keyed scale (Stack's
 *   \`gap\`, Card's \`padding\`). Changing it moves these components only where
 *   that prop value is actually passed.
 */
export interface SpacingUsage {
  components: string[];
  viaProps: string[];
}`;

const usage = deriveSpacingUsage(CORE_SRC);

const entries = Object.entries(usage)
  .map(([token, {components, viaProps}]) => {
    const list = names =>
      names.length === 0 ? '[]' : `[${names.map(n => `'${n}'`).join(', ')}]`;
    return [
      `  '${token}': {`,
      `    components: ${list(components)},`,
      `    viaProps: ${list(viaProps)},`,
      `  },`,
    ].join('\n');
  })
  .join('\n');

const output = [
  HEADER,
  '',
  'export const spacingUsage: Record<string, SpacingUsage> = {',
  entries,
  '};',
  '',
].join('\n');

mkdirSync(dirname(OUT), {recursive: true});
writeFileSync(OUT, output);

const total = Object.keys(usage).length;
console.log(`Generated spacingUsage.ts: ${total} spacing tokens mapped`);
